'use strict';
// Сборка 258: смертность игрока в любом взрослом возрасте.
// Раньше умереть до 76 лет было нельзя при любом здоровье (game.js, nextYear).
//
// Годовой риск: 1% в 72 года у здорового человека, каждый год возраста прибавляет 15%.
// Плохое здоровье умножает риск, но не больше чем в 4 раза: при 60 и выше множителя нет,
// при 30 — ×1.75, при 0 — ×4. Берётся здоровье, сглаженное за несколько лет,
// чтобы один тяжёлый год не решал судьбу, а долгий износ решал.
//
// Калибровка (tools/calibrate_death.js, траектории здоровья по 20 жизням):
// игрок без заботы о здоровье живёт в среднем около 78 лет, до 60 не доживают 2–3%;
// игрок, который держит отдых и лечение в расписании, — около 87.
// До 16 лет игрок не умирает; несчастные случаи в молодости — отдельная будущая механика.

function healthTrend258(){
 if(!Number.isFinite(s.healthTrend258))s.healthTrend258=s.health;
 return s.healthTrend258;
}

function deathChance258(age,trend){
 if(age<16)return 0;
 const frail=Math.max(0,60-trend)/60;
 return Math.min(.9,.01*Math.exp(.15*(age-72))*(1+3*frail*frail));
}

// Вызывается раз в год из nextYear: обновляет сглаженное здоровье и бросает кубик.
function mortality258(){
 const prev=healthTrend258();
 s.healthTrend258=prev+.3*(s.health-prev);
 return Math.random()<deathChance258(s.age,s.healthTrend258);
}
